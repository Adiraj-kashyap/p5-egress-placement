"""Review-1 baseline tables (M09).

Reads the committed M08 outputs and writes docs/review1/baseline_results.md.
Every number in that file comes from results/baselines/runs.csv, except the
B1 tie-break sensitivity totals, which come from the "B1 sensitivity" lines
of results/baselines/run.log (D-039).

    python -m analysis.review1_tables            # write the file
    python -m analysis.review1_tables --check    # regenerate in memory, diff, exit 1 on drift
"""
from __future__ import annotations

import argparse
import csv
import json
import logging
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "results" / "baselines" / "runs.csv"
CONFIG = ROOT / "results" / "baselines" / "config.json"
RUN_LOG = ROOT / "results" / "baselines" / "run.log"
OUT = ROOT / "docs" / "review1" / "baseline_results.md"

METHOD_ORDER = ["B1", "B2-aws", "B2-azure", "B2-gcp", "B2-best"]
TITLES = {
    "t1_three_tier": "T1 three-tier web (measured on the testbed)",
    "t2_pipeline": "T2 data pipeline",
    "t3_microservices": "T3 microservices (Online Boutique shape)",
}
SENS_RE = re.compile(r"B1 sensitivity: last-location-id tie-break gives total ([0-9.]+)")
HEAD_RE = re.compile(r"INFO\s+(\S+@\S+)\s+\(\d+ components")

log = logging.getLogger("review1_tables")


def usd(x: float) -> str:
    return f"{x:,.2f}"


def load_runs() -> list[dict]:
    with RUNS.open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    log.info("read %s: %d rows", RUNS.relative_to(ROOT), len(rows))
    return rows


def load_sensitivity() -> dict[str, float]:
    """instance_id -> B1 total under the opposite (last-location-id) tie-break."""
    out: dict[str, float] = {}
    current = None
    for line in RUN_LOG.read_text(encoding="utf-8").splitlines():
        m = HEAD_RE.search(line)
        if m:
            current = m.group(1)
            continue
        m = SENS_RE.search(line)
        if m and current:
            out[current] = float(m.group(1))
    return out


def regions(assignment_json: str) -> str:
    locs = sorted(set(json.loads(assignment_json).values()))
    return ", ".join(locs)


def render() -> str:
    rows = load_runs()
    cfg = json.loads(CONFIG.read_text(encoding="utf-8"))
    sens = load_sensitivity()

    snaps = sorted({r["snapshot_date"] for r in rows})
    commits = sorted({r["git_commit"] for r in rows})
    by_inst: dict[str, dict[str, dict]] = {}
    for r in rows:
        by_inst.setdefault(r["instance_id"], {})[r["method"]] = r

    L = []
    L.append("# Review 1 — Baseline results (B1, B2)")
    L.append("")
    L.append("<!-- GENERATED by `python -m analysis.review1_tables` from results/baselines/. Do not edit by hand. -->")
    L.append("")
    L.append(f"- **Pricing snapshot:** {', '.join(snaps)} (cost model `{cfg['cost_model_dir']}`)")
    L.append(f"- **Locations:** `{cfg['location_set']}` set, {rows[0]['n_locations']} candidate locations (4 per provider)")
    L.append(f"- **Produced by:** `python -m experiments.run_baselines` at commit `{', '.join(commits)}`, {cfg['created_utc']}")
    L.append(f"- **Cost function:** `placement/cost.py::evaluate`, compute = hourly × {cfg['hours_per_month']} h/month")
    L.append("- **Units:** USD per month. `egress` = inter-component transfer only; `internet` = traffic to end users (D-040)")
    L.append("")

    for inst in sorted(by_inst):
        topo = inst.split("@")[0]
        ms = by_inst[inst]
        n = ms["B1"]["n_components"]
        L.append(f"## {TITLES.get(topo, topo)} — `{inst}`, {n} components")
        L.append("")
        L.append("| Method | Total | Compute | Storage | Egress | Internet | Egress share | Providers | Locations used |")
        L.append("|---|---:|---:|---:|---:|---:|---:|---:|---|")
        for m in METHOD_ORDER:
            r = ms[m]
            L.append(
                f"| {m} | {usd(float(r['total_usd']))} | {usd(float(r['compute_usd']))} | "
                f"{usd(float(r['storage_usd']))} | {usd(float(r['egress_usd']))} | "
                f"{usd(float(r['internet_usd']))} | {float(r['egress_share']) * 100:.1f}% | "
                f"{r['providers_used']} | {regions(r['assignment_json'])} |"
            )
        b1 = float(ms["B1"]["total_usd"])
        best = float(ms["B2-best"]["total_usd"])
        L.append("")
        L.append(f"- B1 vs B2-best: {usd(b1)} vs {usd(best)} USD/month, B1 is {(b1 - best) / best * 100:+.1f}%.")
        if inst in sens:
            L.append(
                f"- B1 under the opposite final tie-break (D-039): {usd(sens[inst])} USD/month "
                f"(from `results/baselines/run.log`)."
            )
        L.append("")

    L.append("## Summary")
    L.append("")
    L.append("| Topology | B1 | B1 (alt tie-break) | B2-aws | B2-azure | B2-gcp | B2-best | B1 egress |")
    L.append("|---|---:|---:|---:|---:|---:|---:|---:|")
    for inst in sorted(by_inst):
        ms = by_inst[inst]
        alt = usd(sens[inst]) if inst in sens else "n/a"
        L.append(
            f"| `{inst}` | {usd(float(ms['B1']['total_usd']))} | {alt} | "
            + " | ".join(usd(float(ms[m]["total_usd"])) for m in METHOD_ORDER[1:])
            + f" | {usd(float(ms['B1']['egress_usd']))} |"
        )
    L.append("")
    L.append("Notes:")
    L.append("")
    L.append("1. aws:us-east-1 and azure:eastus have exactly the same price per vCPU-hour for every shape, so B1 has a tie for "
             "every component. The reported B1 breaks it by the component's own compute+storage bill, then by smallest "
             "location id. This splits T1 and T2 across two providers, and all of B1's egress comes from that split (D-039).")
    L.append("2. No optimum is claimed here. The egress-aware ILP (M10) and the penalty experiment (M15) come next; "
             "H1 will be reported against both B1 variants.")
    L.append("")
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="diff against the committed file; exit 1 on drift")
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(levelname)s %(message)s")

    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current == text:
            print(f"CHECK OK: {OUT.relative_to(ROOT)} matches a fresh render of runs.csv")
            return 0
        import difflib
        sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), text.splitlines(True), "committed", "fresh"))
        print(f"CHECK FAIL: {OUT.relative_to(ROOT)} differs from a fresh render")
        return 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    log.info("wrote %s (%d lines)", OUT.relative_to(ROOT), text.count("\n"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
