"""Results narrative (M18 step 4) -> docs/report/results.md.

The text is a template; every number in it is computed here from the same results files and
formatted with the same functions as `analysis/tables.py`, so it can only quote numbers that
appear in the generated tables (checked by `python -m analysis.check_numbers`). Nothing here
is typed by hand, and no verdict is stated except the one `analysis.verdicts` computed.

    python -m analysis.results_text            # write docs/report/results.md
    python -m analysis.results_text --check    # regenerate in memory, exit 1 on drift
"""
from __future__ import annotations

import argparse
import sys

import pandas as pd

from analysis import figures as F
from analysis import hypotheses as HYP
from analysis import tables as T
from analysis import verdicts as V
from analysis.thresholds import H1_MIN_REDUCTION, H2_MAX_GAP, H2_MIN_SPEEDUP

MAX_WORDS = 1500


def render() -> str:
    t1, t2, t3 = T.TOPOLOGIES
    vs = {v.hid: v for v in V.all_verdicts()}
    vd = {k: v.verdict for k, v in vs.items()}
    h1 = {r.topology_id: r for r in HYP.h1_rows(H1_MIN_REDUCTION) if r.variant == "b1"}
    gap, per_instance = HYP.h2_gap()
    sp, wide = HYP.h2_speedup()
    h3 = {r.topology_id: r for r in HYP.h3_rows() if r.variant == "b1"}
    mins = T.own_cost_minimisers()
    decomp = pd.read_csv(T.RES / "ablation" / "decomposition.csv")
    sens = F.f7_data()
    fr = pd.read_csv(T.RES / "scaling" / "frontier.csv").set_index("location_set")

    def red(t: str) -> str:
        return T.pctv(100 * h1[t].rho.mean)

    def redci(t: str) -> str:
        return T.ci(100 * h1[t].rho.ci_lo, 100 * h1[t].rho.ci_hi)

    def ilp(t: str) -> str:
        return T.usd(h1[t].ilp_usd.mean)

    def step(t: str, i: int, s: float = 1.0) -> str:
        r = decomp[(decomp["topology_id"] == t) & (decomp["step"] == i)
                   & (abs(decomp["traffic_scale"] - s) < T.TOL)].iloc[0]
        return f"{T.usd(r['gain_usd_mean'])} {T.ci(r['gain_usd_ci_lo'], r['gain_usd_ci_hi'], T.usd)}"

    def sav(t: str, mult: float) -> str:
        r = sens[(sens["topology_id"] == t) & (abs(sens["egress_mult"] - mult) < T.TOL)
                 & (sens["locs_per_provider"] == F.F7_BASE_K)].iloc[0]
        return T.pctv(r["mean"])

    n_draws = h1[t1].rho.n
    text = f"""# Results

Generated by `python -m analysis.results_text` from the committed results; do not edit. Every number
below appears in a table in `docs/report/tables/` (checked by `python -m analysis.check_numbers`).
Figures R2-1 and F0-F7 are in `figures/` as PNG, PDF and the CSV of their plotted data. Verdicts and
the rules that produced them: `docs/report/verdicts.md`.

Unless a sentence says otherwise, every figure below is a mean over R = {n_draws} traffic draws with a
95 % bootstrap CI, on the core location set at the price snapshot of 2026-09-21. Methods are compared
**within** a draw, so every interval on a difference is a paired one.

## 1. What the price snapshot implies

Two facts in Table `cost_model.md` drive everything that follows. First, `aws:us-east-1` and
`azure:eastus` cost exactly the same per vCPU-hour (0.0480 USD) for every shape. Second, `azure:eastus`
minimises the *own* cost (compute + storage + internet) of every one of the {mins[t1][0]},
{mins[t2][0]} and {mins[t3][0]} components of T1, T2 and T3 on its own. Because inter-component egress
is never negative and is zero when all components share a location, the all-`azure:eastus` placement is
optimal at any traffic volume. That single structural fact explains both the size of the gain and the
absence of a crossover, and it is a property of this snapshot, not of the method.

## 2. Cost of each method and the size of the gain (H1)

Figure F1 breaks the monthly cost of each method into compute, storage, egress and internet at the
measured or stated traffic (s = 1); R2-1 puts the baselines and the optimiser on the same axes across
the whole traffic range. The exact ILP, proven optimal by CBC on every solve, costs {ilp(t1)},
{ilp(t2)} and {ilp(t3)} USD/month on T1, T2 and T3 — the same as B2-best, the best single-provider
baseline.

B1, the egress-blind baseline, costs {T.usd(h1[t1].b1_usd.mean)}, {T.usd(h1[t2].b1_usd.mean)} and
{T.usd(h1[t3].b1_usd.mean)} USD/month. The vCPU price tie is broken by each component's own storage
bill, which splits T1 and T2 across two providers and makes them pay inter-component egress. The
per-draw reduction (Table `h1_replicated.md`) is {red(t1)}% {redci(t1)}, {red(t2)}% {redci(t2)} and
{red(t3)}% {redci(t3)}. Only T2's interval clears the frozen {100 * H1_MIN_REDUCTION:g}% threshold, and
it clears it narrowly; the one-sided Wilcoxon test agrees (p = {T.pval(h1[t2].wilcoxon_p)} on T2,
p = {T.pval(h1[t1].wilcoxon_p)} on T1 and T3). So **H1 is {vd['H1']} overall and SUPPORTED on T2
alone**. Under the opposite storage tie-break (B1-alt, D-039) B1 is already all-`azure:eastus` and the
reduction is {T.pctv(0.0)}% everywhere, so the verdict does not rest on a tie-break chosen in the
method's favour.

## 3. Where the gain comes from (ablation)

Figure F6 and Table `ablation.md` decompose G = C(B1) - C(ILP) along b1 -> b1_storage ->
ilp_no_edge_egress -> ilp_full. Pricing storage explicitly buys exactly {T.usd(0.0)} on every
topology: B1's tie-break already picks the cheapest storage. Adding user-facing internet egress is
**negative** on T1 ({step(t1, 2)}) and T3 ({step(t3, 2)}) — on its own that ingredient makes the true
cost worse — and only the third step, modelling inter-component egress, recovers it: {step(t1, 3)} on
T1, {step(t2, 3)} on T2 and {step(t3, 3)} on T3. Egress coupling is the largest step at all six
(topology, scale) points. The optimiser's value here is therefore specifically the egress term, not
better unit-price shopping.

## 4. Traffic-scale sweep and the crossover (H3)

Every inter-component volume was multiplied by s over {HYP.n_scale_points()} log-spaced points from
0.01 to 100, on each draw (R2-1, F2, F3). B1's penalty grows steeply with traffic on T1 and T2 while
B1-alt's and B2-best's stay at zero. The ILP optimum uses one provider at every scale and in every
draw: {h3[t1].crossovers}/{h3[t1].n_draws} draws show a crossover on each topology, a rate of
{T.pctv(0.0)}% with a 95 % Wilson interval of {T.ci(100 * h3[t1].rate_lo, 100 * h3[t1].rate_hi)}%
(Table `h1_replicated.md`, section T-H3). No threshold exists at which the optimum collapses from
several providers to one, because it never uses more than one. **H3 is {vd['H3']} on all three
topologies.** Section 1 shows why this is structural rather than a matter of grid resolution: no finer
grid and no further draw can produce a crossover in this snapshot. A topology whose components have
different own-cost minimisers could.

## 5. Scaling and optimality gap (H2)

Table `scaling.md` and Figures F4 and F5 cover synthetic instances with n = 4 to 40 components, five
per cell, on the core ({int(fr.loc['core', 'n_locations'])}) and extended
({int(fr.loc['ext', 'n_locations'])}) location sets. CBC proved optimality on every instance, so the
exact frontier is **not reached within n <= {int(fr.loc['ext', 'largest_n_tested'])}** on either set;
the slowest solve took {T.secs(fr.loc['ext', 'ilp_runtime_max_s_overall'])} s, far below the 600 s
limit.

In the qualifying cells (n >= {HYP.H2_MIN_N}, |L| >= {HYP.H2_MIN_L}) SA's median gap is
{T.pctv(gap.mean)}% over {gap.n} instances with a 95 % CI of {T.ci(gap.ci_lo, gap.ci_hi)}%, comfortably
inside the {100 * H2_MAX_GAP:g}% accuracy clause, and its worst instance median is
{T.pctv(per_instance.max())}%. The speed-up clause fails outright: over the {sp.n} timing instances the
median speed-up is {T.ratio(sp.median)}x with a 95 % CI of {T.ci(sp.ci_lo, sp.ci_hi, T.ratio)}x, so SA
is *slower* than the exact solver at n = 15 and only reaches parity at n = 25, against a requirement of
{H2_MIN_SPEEDUP}x. **H2 is {vd['H2']}** as a conjunction. Greedy with 1-opt runs in milliseconds
(F4) but its gaps are far less reliable (F5). F0 shows SA's convergence on T3 averaged over its seeds:
the mean best-so-far settles just above the ILP optimum, which is why the accuracy clause holds.

## 6. How much of this survives a different price world

Figure F7 and Table `sensitivity.md` move two knobs (D-073). Scaling cross-provider egress prices from
x0.5 to x1.5 moves T2's saving from {sav(t2, 0.5)}% to {sav(t2, 1.5)}% — it crosses the
{100 * H1_MIN_REDUCTION:g}% threshold between x0.75 ({sav(t2, 0.75)}%) and x1 ({sav(t2, 1.0)}%), so
T2's SUPPORTED verdict would not survive a 25 % cut in egress prices. T1 and T3 stay far below the
threshold across the whole range ({sav(t1, 1.5)}% and {sav(t3, 1.5)}% at x1.5). Giving each provider
more regions changes the saving hardly at all, because the winning location is already in the smallest
grid.

## 7. Summary

| Hypothesis | Verdict | Per topology | Key number |
|---|---|---|---|
| H1 ILP >= {100 * H1_MIN_REDUCTION:g}% cheaper than B1 | {vd['H1']} | {', '.join(f"{T.TOPO[t]} {x}" for t, x in vs['H1'].per_topology.items())} | reduction {red(t1)}% / {red(t2)}% / {red(t3)}% |
| H2 SA within {100 * H2_MAX_GAP:g}% and >= {H2_MIN_SPEEDUP}x faster | {vd['H2']} | - | gap {T.pctv(gap.mean)}%, speed-up {T.ratio(sp.median)}x |
| H3 traffic-scale crossover exists | {vd['H3']} | {', '.join(f"{T.TOPO[t]} {x}" for t, x in vs['H3'].per_topology.items())} | {h3[t1].crossovers}/{h3[t1].n_draws} draws |

In this snapshot the optimiser's value is protecting against egress-blind placement, and it is worth
having only where inter-component traffic is large relative to compute: that is T2, where the saving
clears {100 * H1_MIN_REDUCTION:g}%, and not T1 or T3. It is not worth having for finding multi-cloud
splits, because one cheap region already wins every component. Both conclusions are properties of this
price snapshot and these three topologies, and Section 6 shows how far each one travels.
"""
    words = len(text.split())
    if words > MAX_WORDS:
        raise ValueError(f"results.md has {words} words > {MAX_WORDS}")
    return text


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    return T.check_or_write({T.ROOT / "docs" / "report" / "results.md": render()}, args.check,
                            "results_text")


if __name__ == "__main__":
    sys.exit(main())
