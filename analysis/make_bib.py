"""BibTeX for the paper (M21 step 2) -> paper/refs.bib.

Built only from rows of `docs/review1/lit_verification.csv` with `verified=yes` (integrity rule
I3): a paper whose URL was not fetched and whose title and year were not confirmed cannot be
cited. The CSV records the first author only, so every entry lists "<first author> and others";
the venue string is kept as the CSV states it.

    python -m analysis.make_bib            # write paper/refs.bib
    python -m analysis.make_bib --check    # regenerate in memory, exit 1 on drift
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIT = ROOT / "docs" / "review1" / "lit_verification.csv"
OUT = ROOT / "paper" / "refs.bib"


def verified_rows(path: Path = LIT) -> list[dict]:
    with path.open(encoding="utf-8") as f:
        return [r for r in csv.DictReader(f) if r["verified"].strip().lower() == "yes"]


def _ascii(s: str) -> str:
    return unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()


def key(row: dict) -> str:
    """`<lastname><year>`, e.g. `jain2023`; the first title word disambiguates repeats."""
    last = re.sub(r"[^a-z]", "", _ascii(row["first_author"].split()[-1]).lower())
    word = re.sub(r"[^a-z]", "", _ascii(row["title"].split()[0]).lower())
    return f"{last}{row['year']}{word}"


def entry_type(venue: str) -> str:
    v = venue.lower()
    if "thesis" in v:
        return "mastersthesis"
    if "arxiv preprint" in v:
        return "misc"
    if any(w in v for w in ("transactions", "journal", "generation computer systems", "pvldb")):
        return "article"
    return "inproceedings"


def _tex(s: str) -> str:
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def bib_entry(row: dict) -> str:
    t = entry_type(row["venue"])
    venue_field = {"inproceedings": "booktitle", "article": "journal",
                   "mastersthesis": "school", "misc": "howpublished"}[t]
    fields = [("author", f"{row['first_author']} and others"),
              ("title", "{" + row["title"] + "}"),
              (venue_field, row["venue"]),
              ("year", row["year"]),
              ("url", row["url"])]
    body = ",\n".join(f"  {k} = {{{v if k == 'url' else _tex(v)}}}" for k, v in fields)
    return f"@{t}{{{key(row)},\n{body}\n}}\n"


def render(path: Path = LIT) -> str:
    rows = sorted(verified_rows(path), key=lambda r: int(r["row"]))
    head = (f"% generated by `python -m analysis.make_bib` from {LIT.relative_to(ROOT).as_posix()} "
            f"({len(rows)} verified rows); do not edit\n\n")
    return head + "\n".join(bib_entry(r) for r in rows)


def keys(path: Path = LIT) -> set[str]:
    return {key(r) for r in verified_rows(path)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        same = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print(f"refs.bib: {'OK' if same else 'DRIFT'}")
        return 0 if same else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()} ({len(keys())} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
